/**
 * Generates the registry and the marketplace from the mods' own manifests, and validates every
 * preset against the native list. Fails if a preset names a mod that does not exist.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { z } from 'zod'
import { listMods, readJson, ROOT, run } from './lib/repo.mjs'
import { VENDORED } from './lib/vendored.mjs'
import { commandNamesIn } from './lib/builtin-commands.mjs'

const pluginManifest = z.object({
  name: z.string().regex(/^[a-z0-9-]{2,40}$/),
  version: z.string(),
  description: z.string().min(1),
  types: z.string().optional(),
  dependencies: z.array(z.string()).optional(),
})

const preset = z.object({
  id: z.string(),
  description: z.string(),
  mods: z.array(z.string()).min(1),
  config: z.record(z.string(), z.unknown()).optional(),
})

const mods = listMods()
const vendored = VENDORED.filter((name) =>
  existsSync(join(ROOT, 'plugins', name, '.claude-plugin', 'plugin.json')),
)
const names = new Set([...mods.map((mod) => mod.name), ...vendored])
let allOk = true

const sources = [
  ...mods.map((mod) => ({ name: mod.name, dir: mod.dir, base: 'mods' })),
  ...vendored.map((name) => ({ name, dir: join(ROOT, 'plugins', name), base: 'plugins' })),
]
const manifests = sources.map((source) => {
  const parsed = pluginManifest.safeParse(
    readJson(join(source.dir, '.claude-plugin', 'plugin.json')),
  )
  if (!parsed.success) {
    process.stdout.write(`${parsed.error.issues.map((issue) => issue.message).join('; ')}\n`)
    allOk = false
  }
  return {
    ...(parsed.success ? parsed.data : { name: source.name, version: '?', description: '' }),
    path: `${source.base}/${source.name}`,
  }
})

// A session started with --plugin-dir loads only the folders it is given, and a plugin whose
// dependency is absent never loads, so a preset must list every dependency of every mod it names.
function missingDependencies(presetMods) {
  const listed = new Set(presetMods)
  const dependenciesOf = new Map(
    manifests.map((manifest) => [manifest.name, manifest.dependencies ?? []]),
  )
  return presetMods.flatMap((name) =>
    (dependenciesOf.get(name) ?? [])
      .filter((dependency) => !listed.has(dependency))
      .map((dependency) => `${name} needs ${dependency}`),
  )
}

const presetDir = join(ROOT, 'presets')
const presets = existsSync(presetDir)
  ? readdirSync(presetDir)
      .filter((file) => file.endsWith('.json'))
      .sort()
  : []
for (const file of presets) {
  const parsed = preset.safeParse(readJson(join(presetDir, file)))
  if (!parsed.success) {
    allOk =
      run(`preset ${file} (schema)`, { ok: false, note: parsed.error.issues[0]?.message }) && allOk
    continue
  }
  const unknown = parsed.data.mods.filter((name) => !names.has(name))
  const missing = missingDependencies(parsed.data.mods)
  const problems = [
    ...(unknown.length ? [`unknown: ${unknown.join(', ')}`] : []),
    ...(missing.length ? [`missing dependencies: ${missing.join(', ')}`] : []),
  ]
  allOk =
    run(`preset ${parsed.data.id}`, {
      ok: problems.length === 0,
      note: problems.join('; ') || `${parsed.data.mods.length} mods`,
    }) && allOk
}

const GENERATED_MARKER = '<!-- generated by pnpm registry; edit the mod, not this file -->'
const MARKETPLACE_REPO = 'shubhamtaywade82/agentic-mods'

function testStatusOf(mod) {
  const testsDir = join(mod.dir, 'tests')
  const files = existsSync(testsDir)
    ? readdirSync(testsDir).filter((file) => /\.test\.tsx?$/.test(file))
    : []
  if (files.length === 0) return 'Not covered by automated tests yet.'
  return `Covered by \`claude plugin test\` (${files.map((file) => `\`tests/${file}\``).join(', ')}).`
}

// A README per native mod: the directory requires at least 40 words, and the listing stays current.
// A README without the marker was written by hand and is left alone.
for (const mod of mods) {
  const readmePath = join(mod.dir, 'README.md')
  if (existsSync(readmePath) && !readFileSync(readmePath, 'utf8').includes(GENERATED_MARKER))
    continue
  const source = readFileSync(join(mod.dir, 'src', 'register.tsx'), 'utf8')
  const manifest = readJson(join(mod.dir, '.claude-plugin', 'plugin.json'))
  const commands = commandNamesIn(source)
  const typesPath = join(mod.dir, 'types', 'index.d.ts')
  const keys = existsSync(typesPath)
    ? [...readFileSync(typesPath, 'utf8').matchAll(/^\s+(\w+): Shaped</gm)].map((match) => match[1])
    : []
  const body = [
    `# ${mod.name}`,
    '',
    manifest.description,
    '',
    '## Commands',
    '',
    commands.length > 0
      ? commands.map((name) => `- \`/${name}\``).join('\n')
      : 'This mod registers no commands; it acts through hooks and the status line.',
    '',
    '## Shared state',
    '',
    keys.length > 0
      ? `Publishes ${keys.map((key) => `\`${key}\``).join(', ')} for other mods and the engineering cockpit.`
      : 'Keeps its values in the session store only.',
    '',
    '## Configuration',
    '',
    'Reads `.agentic-mods/config.json` when relevant. Invalid fields are reported by `/agentic doctor` and replaced by defaults. See the repository README for the schema.',
    '',
    '## Install',
    '',
    '```',
    `/plugin install ${mod.name} --marketplace ${MARKETPLACE_REPO}`,
    '```',
    '',
    `Mods run with your permissions and are not sandboxed. Read what this one calls with \`claude plugin validate mods/${mod.name}\` before loading it.`,
    '',
    '## Status',
    '',
    `Version ${manifest.version}. Built from the shared core with the engine declarations for Claude Code 2.1.332. ${testStatusOf(mod)}`,
    '',
    GENERATED_MARKER,
    '',
  ].join('\n')
  writeFileSync(readmePath, body)
}

mkdirSync(join(ROOT, 'registry'), { recursive: true })
writeFileSync(
  join(ROOT, 'registry', 'native-mods.json'),
  `${JSON.stringify({ mods: manifests }, null, 2)}\n`,
)

mkdirSync(join(ROOT, '.claude-plugin'), { recursive: true })
const marketplace = {
  name: 'agentic-mods',
  owner: { name: 'shubhamtaywade82' },
  metadata: {
    description:
      'Claude Code mods for engineering workflows: safety, verification, governance and delivery workflows.',
  },
  plugins: manifests.map((item) => ({
    name: item.name,
    source: `./${item.path}`,
    description: item.description,
    version: item.version,
  })),
}
writeFileSync(
  join(ROOT, '.claude-plugin', 'marketplace.json'),
  `${JSON.stringify(marketplace, null, 2)}\n`,
)

writeFileSync(
  join(ROOT, 'registry', 'compatibility.json'),
  `${JSON.stringify(
    {
      claudeCode: '2.1.332',
      declarations: 'plugin-authoring skill, types/claude-code.d.ts for 2.1.332',
      checks: [
        'typecheck (TypeScript 7.0.2, strict)',
        'build (esbuild 0.28.2, bare-import check)',
        'claude plugin validate',
      ],
      notChecked: ['runtime behaviour in the app', 'live-session behaviour beyond the harness'],
    },
    null,
    2,
  )}\n`,
)

allOk =
  run(`registry written: ${manifests.length} mods, ${presets.length} presets`, { ok: true }) &&
  allOk
process.exit(allOk ? 0 : 1)
